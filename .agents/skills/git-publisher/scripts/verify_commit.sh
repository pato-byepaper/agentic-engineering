#!/usr/bin/env bash
# verify_commit.sh
# Verifies that recent or staged commits adhere to git-publisher guidelines:
# 1. No AI Co-Author trailers (Co-authored-by: ... <...ai...> or bot)
# 2. No AI-generated or assistant watermarks
# 3. Follows conventional commit format (feat, fix, refactor, test, docs, chore, etc.)

set -euo pipefail

TARGET_REF="${1:-HEAD}"

echo "==> Auditing commit message for: $TARGET_REF"

if ! git rev-parse --verify "$TARGET_REF" >/dev/null 2>&1; then
    echo "No commits found to verify. Skipping."
    exit 0
fi

COMMIT_MSG=$(git log -1 --pretty=%B "$TARGET_REF")
COMMIT_SUBJECT=$(git log -1 --pretty=%s "$TARGET_REF")

# 1. Check for AI Co-Authorship trailers
if echo "$COMMIT_MSG" | grep -Ei "Co-authored-by:.*(bot|ai|agent|assistant|copilot|gemini|antigravity)" >/dev/null; then
    echo "❌ ERROR: Detected forbidden AI Co-Authored trailer in commit message:"
    echo "$COMMIT_MSG" | grep -Ei "Co-authored-by:"
    exit 1
fi

# 2. Check for AI watermarks
if echo "$COMMIT_MSG" | grep -Ei "(generated by ai|assisted by ai|created by agent|ai generated)" >/dev/null; then
    echo "❌ ERROR: Detected forbidden AI watermark in commit message."
    exit 1
fi

# 3. Check conventional commit format
CONVENTIONAL_REGEX="^(feat|fix|refactor|test|docs|style|perf|chore|ci|build)(\([a-zA-Z0-9_-]+\))?: .+"
if [[ ! "$COMMIT_SUBJECT" =~ $CONVENTIONAL_REGEX ]]; then
    echo "⚠️  WARNING: Commit subject does not strictly follow Conventional Commits (e.g. feat(scope): message):"
    echo "   Subject: $COMMIT_SUBJECT"
else
    echo "✅ Commit subject follows Conventional Commits."
fi

echo "✅ All commit authoring checks passed. Clean and professional!"
exit 0
